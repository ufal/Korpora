#!/usr/bin/env python3
"""Writes Korpora/Korpora/Documents/UnicodeScriptData.swift from Unicode's Scripts.txt.

Usage: scripts/generate-unicode-scripts.py [Scripts.txt]    (downloads the latest one when no file is given)
Run it again for a new Unicode version (docs/typography.md).
"""
import re, sys, urllib.request, pathlib

URL = "https://www.unicode.org/Public/UCD/latest/ucd/Scripts.txt"
source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8") if len(sys.argv) > 1 \
    else urllib.request.urlopen(URL).read().decode("utf-8")
version = (re.search(r"# Scripts-([\d.]+)\.txt", source) or [None, "unknown"])[1]

ranges = []
for line in source.splitlines():
    m = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)", line)
    if m:
        lo = int(m.group(1), 16)
        hi = int(m.group(2) or m.group(1), 16)
        ranges.append((lo, hi, m.group(3)))
ranges.sort()
# merge neighbours with the same script
merged = []
for lo, hi, name in ranges:
    if merged and merged[-1][2] == name and merged[-1][1] + 1 == lo:
        merged[-1] = (merged[-1][0], hi, name)
    else:
        merged.append((lo, hi, name))
names = sorted({n for _, _, n in merged})
index = {n: i for i, n in enumerate(names)}

def array(type_, values, per_line=12):
    rows = [", ".join(values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return f"[{type_}]" + " = [\n        " + ",\n        ".join(rows) + ",\n    ]"

out = f'''// Generated by scripts/generate-unicode-scripts.py from Unicode {version} Scripts.txt. Do not edit.
//
// Unicode Data Files, Copyright (c) Unicode, Inc. Distributed under the Unicode License v3
// (https://www.unicode.org/license.txt).

enum UnicodeScriptData {{
    /// Script names as Unicode writes them (`Latin`, `Han`, `Old_Italic`), sorted.
    static let names: {array("String", ['"%s"' % n for n in names], 6)}

    /// The ranges, sorted: `starts[i]...ends[i]` belongs to `names[scriptIndex[i]]`. Code points in no range are Unknown.
    static let starts: {array("UInt32", ["0x%X" % lo for lo, _, _ in merged])}

    static let ends: {array("UInt32", ["0x%X" % hi for _, hi, _ in merged])}

    static let scriptIndex: {array("UInt16", [str(index[n]) for _, _, n in merged], 24)}
}}
'''
dest = pathlib.Path(__file__).resolve().parent.parent / "Korpora/Korpora/Documents/UnicodeScriptData.swift"
dest.write_text(out, encoding="utf-8")
print(f"{dest}: {len(names)} scripts, {len(merged)} ranges (Unicode {version})")
