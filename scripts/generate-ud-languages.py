#!/usr/bin/env python3
"""Generates KorporaEngine/Sources/KorporaEngine/UDLanguages.swift from the Universal Dependencies language table
(https://github.com/UniversalDependencies/docs-automation/blob/master/codes_and_flags.yaml).

The import of UD files (UDMetadata.swift) puts a language's name, ISO 639-3 code, family, genus (the branch of the
family) and script into the `text` region of each treebank file, so a search or a subcorpus can ask for "Slavic" or
"Cyrillic". Run this when UD's table changes (new languages come with each release):

    scripts/generate-ud-languages.py                 # fetches the table from GitHub
    scripts/generate-ud-languages.py codes_and_flags.yaml   # or from a local copy

No YAML library is needed: the table is a flat mapping of language name to `key: value` lines.
"""
import datetime
import sys
import urllib.request
from pathlib import Path

URL = "https://raw.githubusercontent.com/UniversalDependencies/docs-automation/master/codes_and_flags.yaml"
OUT = Path(__file__).resolve().parent.parent / "KorporaEngine/Sources/KorporaEngine/UDLanguages.swift"
# UD abbreviates this one family; a value in a list of choices should be readable.
FAMILY_NAMES = {"IE": "Indo-European"}


def load(text):
    languages, current = {}, None
    for raw in text.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if not raw.startswith(" "):
            current = languages.setdefault(raw.rstrip().rstrip(":").strip().strip("\"'"), {})
            continue
        key, _, value = raw.strip().partition(":")
        value = value.strip()
        if value.startswith("["):
            value = [item.strip().strip("\"'") for item in value.strip("[]").split(",") if item.strip()]
        else:
            value = value.strip("\"'")
        current[key] = value
    return languages


def swift(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) > 1:
        source = Path(sys.argv[1]).read_text(encoding="utf-8")
        where = sys.argv[1]
    else:
        source = urllib.request.urlopen(URL, timeout=60).read().decode("utf-8")
        where = URL
    languages = load(source)
    rows = []
    for name, entry in languages.items():
        code = entry.get("lcode", "").lower()
        if not code:
            print(f"no lcode for {name}: skipped", file=sys.stderr)
            continue
        scripts = entry.get("scripts") or []
        family = entry.get("family", "")
        genus = entry.get("genus")
        rows.append((code, name, entry.get("iso3", ""), FAMILY_NAMES.get(family, family), genus, scripts[0] if scripts else ""))
    rows.sort()
    codes = [r[0] for r in rows]
    assert len(codes) == len(set(codes)), "a language code is used twice"
    lines = [
        "// Generated by scripts/generate-ud-languages.py - do not edit.",
        f"// Source: {where} ({len(rows)} languages, {datetime.date.today().isoformat()})",
        "",
        "/// What Universal Dependencies knows about each of its languages, by the language code that starts the names",
        "/// of its files (`cs` in `cs_pdt-ud-train.conllu`). `script` is the first one UD lists for the language.",
        "enum UDLanguages {",
        "    struct Entry: Sendable, Equatable {",
        "        let name: String",
        "        let iso3: String",
        "        let family: String",
        "        /// The branch of the family (Germanic, Slavic, ...); nil where UD gives none (isolates, some families).",
        "        let genus: String?",
        "        /// An ISO 15924 code: Latn, Cyrl, Arab, ...",
        "        let script: String",
        "    }",
        "",
        "    static let byCode: [String: Entry] = [",
    ]
    for code, name, iso3, family, genus, script in rows:
        genus_text = swift(genus) if genus else "nil"
        lines.append(f"        {swift(code)}: Entry(name: {swift(name)}, iso3: {swift(iso3)}, family: {swift(family)}, "
                     f"genus: {genus_text}, script: {swift(script)}),")
    lines += ["    ]", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(rows)} languages -> {OUT}")


main()
